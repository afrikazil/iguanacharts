/**
 * Уровни инвалидации. Кадровый цикл копит максимум за кадр, поэтому движение
 * мыши не тянет за собой перерисовку серий.
 */
export const Invalidation = {
    /** Нечего перерисовывать. */
    None: 0,
    /** Только оверлей: кросс-хэйр, подписи под курсором. */
    Cursor: 1,
    /** Геометрия та же, изменились цвета/подсветка — перерисовать слой серий. */
    Light: 2,
    /** Изменились данные или трансформация — пересчитать геометрию и всё перерисовать. */
    Full: 3,
} as const;

export type InvalidationLevel = (typeof Invalidation)[keyof typeof Invalidation];
